    private void tampilkanData() {
        List<Mahasiswa> listMhs = mahasiswaService.getAll();
        
        javax.swing.DefaultListModel<String> listIdModel = new javax.swing.DefaultListModel<>();
        javax.swing.DefaultListModel<String> listNamaModel = new javax.swing.DefaultListModel<>();
        
        for (Mahasiswa mhs : listMhs) {
             listIdModel.addElement(String.valueOf(mhs.getId()));
             listNamaModel.addElement(mhs.getNama());
        }
        
        jList1.setModel(listIdModel);
        jList2.setModel(listNamaModel);
    }

