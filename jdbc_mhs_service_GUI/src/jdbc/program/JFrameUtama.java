    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String nama = jTextField1.getText();
        if (!nama.isEmpty()) {
            Mahasiswa mhsBaru = mahasiswaService.makeMhsObject(); 
            mhsBaru.setNama(nama); 

            mahasiswaService.add(mhsBaru); 

            jTextField1.setText(""); // Kosongkan input
            tampilkanData(); // Refresh tampilan
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            int id = Integer.parseInt(jTextField2.getText()); // Ambil ID
            String namaBaru = jTextField3.getText(); // Ambil Nama baru

            Mahasiswa mhsUpdate = mahasiswaService.getById(id); 
            if (mhsUpdate != null) {
                mhsUpdate.setNama(namaBaru); 
                mahasiswaService.update(mhsUpdate); 

                jTextField2.setText("");
                jTextField3.setText("");
                tampilkanData(); 
            }
        } catch (NumberFormatException e) {
            System.out.println("ID tidak valid");
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        try {
            int id = Integer.parseInt(jTextField4.getText()); // Ambil ID hapus

            mahasiswaService.delete(id); 

            jTextField4.setText(""); // Kosongkan input
            tampilkanData(); 
        } catch (NumberFormatException e) {
            System.out.println("ID tidak valid");
        }
    }//GEN-LAST:event_jButton4ActionPerformed

